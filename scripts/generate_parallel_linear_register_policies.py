#!/usr/bin/env python3
"""Render the seven reviewed, frozen BUILD register policies (never learn online)."""
from __future__ import annotations
import argparse,hashlib,json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
PROFILES=('gr00t_z2_register_policy','lingbot2_multiview_w8_register_policy',
 'qwen3vl_pooler_z1_register_policy','qwen3vl_pooler_ds1_register_policy',
 'qwen3vl_pooler_ds3_register_policy','qwen3vl_pooler_ds3_partial_mrope_register_policy',
 'groot_n17_pooler_ds3_register_policy')
FIELDS=('node_count','dma_count','barrier_count','kernel_count','typed_kernel_count',
 'no_ddr_kernel_count','operand_count','weight_operand_count','key_cache_operand_count',
 'value_cache_operand_count','semantic_input_operand_count','ordered_node_kind_hash','ordered_kernel_hash')
ROLES={1:'ModelWeight',2:'KeyCache',3:'ValueCache',4:'SemanticInput',5:'Int8ModelWeight',
 6:'PerChannelScale',7:'Fp8ModelWeight',8:'PackedInt4ModelWeight',9:'PackedFp4ModelWeight',
 10:'Fp8BlockScale',11:'Fp32PerChannelScale',12:'PackedUint4ModelWeight',13:'PerGroupScale',14:'NegativeZeroPoint'}
KINDS={1:'TypedDdr',2:'IntrinsicNoDdr',3:'ExplicitNoDdr'}
PROOFS={0:'None',2:'AllGatherSpm',4:'FillSpm',5:'SliceSpm',6:'RingAllReduceSpmResidual'}

def validate_profile(profile):
 total, phases, rules = profile['total'], profile['phases'], profile['rules']
 assert phases and rules
 assert len({r['kernel'] for r in rules}) == len(rules)
 assert len({p['phase'] for p in phases}) == len(phases)
 for stats in [total, *phases]:
  assert all(isinstance(stats[f], int) and stats[f] >= 0 for f in FIELDS)
  assert stats['node_count'] >= sum(stats[f] for f in ('dma_count', 'barrier_count', 'kernel_count'))
  assert stats['kernel_count'] == stats['typed_kernel_count'] + stats['no_ddr_kernel_count']
  assert stats['operand_count'] == sum(stats[f] for f in (
   'weight_operand_count', 'key_cache_operand_count', 'value_cache_operand_count', 'semantic_input_operand_count'))
  assert all(0 < stats[f] < (1 << 64) for f in FIELDS if f.startswith('ordered_'))
 for field in FIELDS:
  if not field.startswith('ordered_'):
   assert total[field] == sum(p[field] for p in phases), field
 expected = {f: 0 for f in FIELDS if 'kernel_count' in f or 'operand_count' in f}
 for rule in rules:
  count = rule['count']
  assert isinstance(count, int) and count > 0
  assert rule['kind'] in KINDS and rule['proof'] in PROOFS
  assert rule['dynamic'] == (rule['kernel'] in ('fill', 'slice_single_axis', 'binary_1xC_NxC_tileC'))
  typed = rule['kind'] == 1
  assert bool(rule['operands']) == typed
  assert (rule['proof'] == 0) == (rule['kind'] != 3)
  expected['kernel_count'] += count
  expected['typed_kernel_count' if typed else 'no_ddr_kernel_count'] += count
  registers = set()
  for role, access, encoding, lo, hi in rule['operands']:
   assert role in ROLES and access in (1, 2) and encoding == 1
   assert 0 <= lo < hi < 64 and lo % 2 == 0 and hi == lo + 1
   assert not registers.intersection((lo, hi))
   registers.update((lo, hi))
   expected['operand_count'] += count
   expected[{2:'key_cache_operand_count',3:'value_cache_operand_count',4:'semantic_input_operand_count'}.get(role,'weight_operand_count')] += count
 assert all(total[field] == count for field, count in expected.items()), (total, expected)

def render(data):
 assert data['schema']=='parallel_linear_register_census.v1'
 assert set(data['profiles'])==set(PROFILES)
 lines=['// Generated by scripts/generate_parallel_linear_register_policies.py.',
 '// Frozen from independently captured and reviewed BUILD streams. No runtime learning.',
 '#pragma once','#include "graph/graph_runtime.h"','#include "core/rpu_kernel_cache.h"',
 '#include <cstring>','#include <iterator>','namespace rpu_pl_census {',
 '''inline GraphKernelRegisterRule rule(const char* name, size_t count,
    GraphKernelRegisterRuleKind kind, GraphKernelNoDdrProof proof,
    std::vector<GraphDdrRegisterAbi> operands, bool dynamic) {
  GraphKernelRegisterRule value;
  if (dynamic) value.kernel_name = name;
  else {
    for (size_t i = 0; i < std::size(KERNEL_ID_NAMES); ++i) {
      if (std::strcmp(KERNEL_ID_NAMES[i], name) == 0) {
        TORCH_CHECK(!value.kernel_id.has_value(), "duplicate frozen census name: ", name);
        value.kernel_id = static_cast<KernelId>(i);
      }
    }
    TORCH_CHECK(value.kernel_id.has_value(), "frozen census kernel is unregistered: ", name);
  }
  value.expected_count = count; value.kind = kind; value.no_ddr_proof = proof;
  value.operands = std::move(operands); return value;
}''']
 for name in PROFILES:
  profile=data['profiles'][name]
  validate_profile(profile)
  semantic={key:profile[key] for key in ('total','phases','rules')}
  canonical=json.dumps(semantic,sort_keys=True,separators=(',',':')).encode()
  identity=int.from_bytes(hashlib.sha256(canonical).digest()[:8],'big')
  lines += [f'inline const GraphKernelRegisterPolicy& {name}() {{','  static const auto value = [] {',
            '    GraphKernelRegisterPolicy p;',f'    p.name = "{name}_n32k32_v1";',f'    p.fingerprint = UINT64_C(0x{identity:016x});','    p.rules = {']
  for r in profile['rules']:
   ops=[]
   for role,access,encoding,lo,hi in r['operands']:
    assert encoding==1 and hi==lo+1 and lo%2==0
    ops.append('{GraphDdrRegisterRole::'+ROLES[role]+', GraphDdrRegisterAccess::'+{1:'Read',2:'Write'}[access]+f', GraphDdrRegisterEncoding::DevAddrShift8LoHi, {lo}, {hi}'+'}')
   assert r['count']>0
   lines.append(f'      rule("{r["kernel"]}", {r["count"]}, GraphKernelRegisterRuleKind::{KINDS[r["kind"]]}, GraphKernelNoDdrProof::{PROOFS[r["proof"]]}, '+'{'+', '.join(ops)+'}, '+str(r['dynamic']).lower()+'),')
  lines+=['    };']
  for field in FIELDS:
   value=profile['total'][field];expr=f'UINT64_C(0x{value:016x})' if field.startswith('ordered_') else str(value)
   lines.append(f'    p.expected_{field} = {expr};')
  for phase in profile['phases']:
   lines+=['    { GraphKernelRegisterPhaseExpectation phase;',f'      phase.name = "{phase["phase"]}";']
   for field in FIELDS:
    value=phase[field];expr=f'UINT64_C(0x{value:016x})' if field.startswith('ordered_') else str(value)
    lines.append(f'      phase.stats.{field} = {expr};')
   lines+=['      p.phases.push_back(std::move(phase)); }']
  lines+=['    return p;','  }();','  return value;','}']
 lines+=['inline const GraphKernelRegisterPolicy& policy(const char* profile) {']
 for name in PROFILES:lines.append(f'  if (std::strcmp(profile, "{name}") == 0) return {name}();')
 lines+=['  TORCH_CHECK(false, "unknown frozen parallel_linear census profile: ", profile);','}','}  // namespace rpu_pl_census','']
 return '\n'.join(lines)

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--manifest',type=Path,default=ROOT/'tests/fixtures/parallel_linear_register_census.v1.json');p.add_argument('--output',type=Path,default=ROOT/'src/fused/rpu_parallel_linear_register_policies.h');p.add_argument('--check',action='store_true');a=p.parse_args()
 text=render(json.loads(a.manifest.read_text()))
 if a.check:
  if a.output.read_text()!=text:raise SystemExit('generated register policies are stale')
 else:a.output.write_text(text)
if __name__=='__main__':main()
