// Parallel Linear host ABI (registers 0..23). Weight and scale are raw device
// addresses here; zero is valid when a graph DDR writer fills the corresponding
// register pair after this helper returns.
struct ParallelLinearRegisterArgs {
  uint32_t input_spm_addr;
  uint64_t weight_dev_addr;
  uint32_t output_spm_addr;
  uint32_t bias_spm_addr;
  uint32_t local_m;
  uint32_t local_n;
  uint32_t local_k;
  uint16_t has_bias;
  uint16_t num_cores;
  uint32_t input_m_byte_step;
  uint32_t output_m_byte_step;
  uint64_t scale_dev_addr;
  uint16_t partition;
  uint16_t dtype_mode;
};

template <typename Kernel>
inline void set_u32_reg_pair(Kernel& kernel, int lo_reg, uint64_t value) {
  kernel.set_regs(lo_reg, static_cast<uint16_t>(value & 0xffffu));
  kernel.set_regs(lo_reg + 1, static_cast<uint16_t>((value >> 16) & 0xffffu));
}

template <typename Kernel>
inline void set_parallel_linear_regs(Kernel& kernel,
                                     const ParallelLinearRegisterArgs& a) {
  set_u32_reg_pair(kernel, 0, a.input_spm_addr);
  set_u32_reg_pair(kernel, 2, a.weight_dev_addr >> 8);
  set_u32_reg_pair(kernel, 4, a.output_spm_addr);
  set_u32_reg_pair(kernel, 6, a.bias_spm_addr);
  kernel.set_regs(8, static_cast<uint16_t>(a.local_m));
  kernel.set_regs(9, 0);
  set_u32_reg_pair(kernel, 10, a.local_n);
  kernel.set_regs(12, static_cast<uint16_t>(a.local_k));
  kernel.set_regs(13, static_cast<uint16_t>(a.local_k / 16));
  kernel.set_regs(14, a.has_bias);
  kernel.set_regs(15, a.num_cores);
  set_u32_reg_pair(kernel, 16, a.input_m_byte_step);
  set_u32_reg_pair(kernel, 18, a.output_m_byte_step);
  set_u32_reg_pair(kernel, 20, a.scale_dev_addr >> 8);
  kernel.set_regs(22, a.partition);
  kernel.set_regs(23, a.dtype_mode);
}

struct ParallelLinearInt4GroupRegisterArgs {
  ParallelLinearRegisterArgs linear;
  uint16_t group_size;
  uint16_t local_groups;
  uint32_t scale_group_block_byte_step;
};

template <typename Kernel>
inline void set_parallel_linear_int4_group_regs(
    Kernel& kernel, const ParallelLinearInt4GroupRegisterArgs& a) {
  set_parallel_linear_regs(kernel, a.linear);
  kernel.set_regs(24, a.group_size);
  kernel.set_regs(25, a.local_groups);
  set_u32_reg_pair(kernel, 26, a.scale_group_block_byte_step);
}

