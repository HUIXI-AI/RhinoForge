inline constexpr int kFallbackNeighbors = 5;
inline constexpr double kFallbackDistanceEpsilon = 0.01;
inline constexpr std::array<int, 7> kTileGrid{32, 48, 64, 80, 96, 112, 128};

inline int ceil_div_positive(int value, int divisor) {
  return value / divisor + (value % divisor != 0);
}

// Fallback selector for positive shapes absent from an exact table.
inline int measured_neighbor_tile(const PLEntry* table, std::size_t count,
                                  int m, int local_n, int local_k,
                                  int (*m_tile)(int)) {
  if (m <= 0 || local_n <= 0 || local_k <= 0) {
    throw std::invalid_argument("ParallelLinear dimensions must be positive");
  }

  std::array<int, kTileGrid.size()> candidates{};
  std::size_t candidate_count = 0;
  for (int tile : kTileGrid) {
    if (m_tile(tile) >= m) candidates[candidate_count++] = tile;
  }
  if (candidate_count == 0) {
    candidates = kTileGrid;
    candidate_count = candidates.size();
  }

  auto candidate_index = [&](int tile) {
    for (std::size_t i = 0; i < candidate_count; ++i) {
      if (candidates[i] == tile) return static_cast<int>(i);
    }
    return -1;
  };

  std::vector<std::pair<double, int>> neighbours;
  neighbours.reserve(count);
  for (std::size_t i = 0; i < count; ++i) {
    const PLEntry& e = table[i];
    if (candidate_index(e.tile) < 0) continue;
    const double dm = std::log2(static_cast<double>(m) / e.M);
    const double dn = 4.0 * std::log2(static_cast<double>(local_n) / e.n);
    const double dk = 0.5 * std::log2(static_cast<double>(local_k) / e.k);
    neighbours.emplace_back(dm * dm + dn * dn + dk * dk, e.tile);
  }
  std::stable_sort(neighbours.begin(), neighbours.end(),
                   [](const auto& lhs, const auto& rhs) {
                     return lhs.first < rhs.first;
                   });

  auto physical_key = [&](std::size_t i) {
    const int tile = candidates[i];
    return std::make_tuple(ceil_div_positive(m, m_tile(tile)),
                           ceil_div_positive(local_n, tile) * tile, tile);
  };
  if (neighbours.empty()) {
    std::size_t best = 0;
    for (std::size_t i = 1; i < candidate_count; ++i) {
      if (physical_key(i) < physical_key(best)) best = i;
    }
    return candidates[best];
  }

  std::array<double, kTileGrid.size()> votes{};
  const std::size_t vote_count =
      std::min<std::size_t>(kFallbackNeighbors, neighbours.size());
  for (std::size_t i = 0; i < vote_count; ++i) {
    const int index = candidate_index(neighbours[i].second);
    votes[static_cast<std::size_t>(index)] +=
        1.0 / (neighbours[i].first + kFallbackDistanceEpsilon);
  }

  auto ranked_key = [&](std::size_t i) {
    return std::tuple_cat(std::make_tuple(-votes[i]), physical_key(i));
  };
  std::size_t best = 0;
  for (std::size_t i = 1; i < candidate_count; ++i) {
    if (ranked_key(i) < ranked_key(best)) best = i;
  }
  return candidates[best];
}

struct LinearTileOverrides {
  bool gy1;
  int force_w16, m64_w16, m384w_w16, m384n_w16, vis_w16;
  int force_w8, m64_w8, m64n_w8, m384w_w8, vis_w8;
};

inline const LinearTileOverrides& linear_tile_overrides() {
  static const LinearTileOverrides value = [] {
    auto integer = [](const char* name) {
      const char* e = std::getenv(name);
      return (e && *e) ? std::atoi(e) : -1;
    };
    const char* gy1 = std::getenv("RPU_LINEAR_TILE_GY1");
    const std::string gy1_value = gy1 ? gy1 : "";
    return LinearTileOverrides{
        gy1_value == "1" || gy1_value == "true",
        integer("RPU_LINEAR_TILE_FORCE"),
        integer("RPU_LINEAR_TILE_M64"),
        integer("RPU_LINEAR_TILE_M384W"),
        integer("RPU_LINEAR_TILE_M384N"),
        integer("RPU_LINEAR_TILE_VIS"),
        integer("RPU_LINEAR_TILE_W8_FORCE"),
        integer("RPU_LINEAR_TILE_W8_M64"),
        integer("RPU_LINEAR_TILE_W8_M64N"),
        integer("RPU_LINEAR_TILE_W8_M384W"),
        integer("RPU_LINEAR_TILE_W8_VIS")};
  }();
  return value;
}

inline int prefer_single_m_tile(int local_m, int pick, int (*m_tile)(int)) {
  if (!linear_tile_overrides().gy1 || m_tile(pick) >= local_m) return pick;
  static constexpr int kTiles[] = {128, 112, 96, 80, 64, 48, 32};
  for (int tile : kTiles) {
    if (m_tile(tile) >= local_m) return tile;
  }
  return pick;
}

inline TilePick select_tile_acc16(int M, int local_n, int local_k, bool is_fp16) {
  const auto& override = linear_tile_overrides();
  const int forced = is_fp16 ? override.force_w16 : override.force_w8;
  if (forced > 0) {
    return {forced, is_fp16 ? mtile_w16(forced) : mtile_w8a16(forced)};
  }
  const PLEntry* table = is_fp16 ? PL_EXACT_W16 : PL_EXACT_W8A16;
  const std::size_t count = is_fp16 ? table_size(PL_EXACT_W16)
                                     : table_size(PL_EXACT_W8A16);
  int n = exact_lookup(table, count, M, local_n, local_k);
  if (n == 0 && is_fp16) {
    int scoped = -1;
    if (M <= 64) scoped = override.m64_w16;
    else if (M <= 384 && (local_n + 1) / 2 > 128)
      scoped = override.m384w_w16;
    else if (M <= 384)
      scoped = override.m384n_w16;
    else
      scoped = override.vis_w16;
    n = scoped > 0
        ? scoped
        : prefer_single_m_tile(
              M, measured_neighbor_tile(table, count, M, local_n, local_k,
                                        mtile_w16),
              mtile_w16);
  } else if (n == 0) {
    int scoped = -1;
    if (M <= 64 && local_n > 128) scoped = override.m64_w8;
    else if (M <= 64) scoped = override.m64n_w8;
    else if (M <= 384 && local_n > 384) scoped = override.m384w_w8;
    else if (M > 384) scoped = override.vis_w8;
    n = scoped > 0
        ? scoped
        : measured_neighbor_tile(table, count, M, local_n, local_k,
                                 mtile_w8a16);
  }
  return {n, is_fp16 ? mtile_w16(n) : mtile_w8a16(n)};
}

inline TilePick select_tile_acc32(int M, int local_n, int local_k, bool is_fp16) {
  const PLEntry* table = is_fp16 ? PL_EXACT_FP16_ACC32
                                 : PL_EXACT_W8A16_ACC32;
  const std::size_t count = is_fp16 ? table_size(PL_EXACT_FP16_ACC32)
                                     : table_size(PL_EXACT_W8A16_ACC32);
  int n = exact_lookup(table, count, M, local_n, local_k);
  if (n == 0) {
    n = measured_neighbor_tile(
        table, count, M, local_n, local_k,
        is_fp16 ? mtile_fp16_acc32 : mtile_w8a16_acc32);
  }
  return {n, is_fp16 ? mtile_fp16_acc32(n) : mtile_w8a16_acc32(n)};
}

