struct PLEntry { int M, n, k, tile; };
struct TilePick { int n_tile; int m_tile; };

// Shared Full-local-K W8A16 row schedule for an exact admitted geometry.
// This does not extend the generated auto-tile tables.
// Payload availability, precision, layouts and buffer lifetimes are separate
// owner/launcher contracts. Other shapes keep the existing auto-tile route.
inline constexpr bool supports_w8a16_row_weight_reuse(
    int64_t M, int64_t N, int64_t K, int partition, int num_cores) noexcept {
  return M == 512 && N == 1024 && K == 2048 && partition == 0 &&
         num_cores == 8;
}

template <std::size_t N>
constexpr std::size_t table_size(const PLEntry (&)[N]) { return N; }

inline uint64_t pl_key(int M, int n, int k) {
  return (static_cast<uint64_t>(static_cast<uint32_t>(M)) << 34) |
         (static_cast<uint64_t>(static_cast<uint32_t>(n)) << 17) |
         static_cast<uint64_t>(static_cast<uint32_t>(k));
}

// Tables are emitted in key order, so lookup is allocation-free, thread-safe,
// and O(log N). This is on the host launch path and is called for every Linear.
inline int exact_lookup(const PLEntry* table, std::size_t count,
                        int M, int local_n, int local_k) {
  const uint64_t wanted = pl_key(M, local_n, local_k);
  std::size_t lo = 0;
  std::size_t hi = count;
  while (lo < hi) {
    const std::size_t mid = lo + (hi - lo) / 2;
    const PLEntry& e = table[mid];
    if (pl_key(e.M, e.n, e.k) < wanted) lo = mid + 1;
    else hi = mid;
  }
  if (lo == count) return 0;
  const PLEntry& e = table[lo];
  return pl_key(e.M, e.n, e.k) == wanted ? e.tile : 0;
}

